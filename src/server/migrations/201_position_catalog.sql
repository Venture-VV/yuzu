CREATE TABLE org_departments (
  key   text PRIMARY KEY CHECK (key ~ '^[a-z]+$'),
  name  text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 40),
  sort  integer NOT NULL
);

CREATE TABLE position_catalog (
  key             text PRIMARY KEY CHECK (key ~ '^[a-z]+(\.(lead|staff))?$'),
  department      text NOT NULL REFERENCES org_departments (key),
  title           text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 40),
  level           text NOT NULL CHECK (level IN ('super', 'senior', 'admin')),
  sort            integer NOT NULL,
  -- 总裁：固定拥有全部权限，没有建议权限这一说
  all_permissions boolean NOT NULL DEFAULT false,
  updated_at      timestamptz NOT NULL DEFAULT now(),
  updated_by      bigint REFERENCES staff (id)
);

CREATE TABLE position_suggestions (
  position_key text NOT NULL REFERENCES position_catalog (key),
  permission   text NOT NULL CHECK (permission ~ '^[a-zA-Z]+\.[a-zA-Z]+$'),
  PRIMARY KEY (position_key, permission)
);

CREATE TABLE position_config_log (
  id           bigserial PRIMARY KEY,
  at           timestamptz NOT NULL DEFAULT now(),
  staff_id     bigint REFERENCES staff (id),
  action       text NOT NULL CHECK (action IN ('init', 'suggestions', 'restore', 'legacy_migrate')),
  position_key text REFERENCES position_catalog (key),
  detail       jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX position_config_log_at_idx ON position_config_log (at DESC);
CREATE TRIGGER position_config_log_immutable BEFORE UPDATE OR DELETE ON position_config_log FOR EACH ROW EXECUTE FUNCTION yuzu_forbid_mutation();

